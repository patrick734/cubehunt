// Writes ABIs and the live deployment into the app (app/src/generated). Run after every deploy.
const fs = require("fs");
const path = require("path");

const ART = path.join(__dirname, "..", "artifacts", "src");
const OUT = path.join(__dirname, "..", "..", "app", "src", "generated");
const C = {
  huntAbi: "CubeHunt.sol/CubeHunt.json",
  vaultsAbi: "CubeVaults.sol/CubeVaults.json",
  pointsAbi: "CubePoints.sol/CubePoints.json",
  governorAbi: "CubeGovernor.sol/CubeGovernor.json",
  buyBurnAbi: "CubeBuyBurn.sol/CubeBuyBurn.json",
  timelockAbi: "CubeTimelock.sol/CubeTimelock.json",
};
fs.mkdirSync(OUT, { recursive: true });
let abis = "// Generated by contracts/scripts/export-abis.js. Do not edit.\n\n";
for (const [name, file] of Object.entries(C)) {
  const { abi } = JSON.parse(fs.readFileSync(path.join(ART, file), "utf8"));
  abis += `export const ${name} = ${JSON.stringify(abi)} as const;\n\n`;
}
fs.writeFileSync(path.join(OUT, "abis.ts"), abis);

const file = process.env.DEPLOYMENT_FILE || path.join(__dirname, "..", "deployments", "robinhood.json");
let dep = null;
if (fs.existsSync(file)) {
  const { sources, ...rest } = JSON.parse(fs.readFileSync(file, "utf8"));
  dep = rest;
}
fs.writeFileSync(
  path.join(OUT, "deployment.ts"),
  "// Generated by contracts/scripts/export-abis.js. Do not edit.\n\n" +
    `export const deployment = ${JSON.stringify(dep, null, 2)} as Deployment | null;\n\n` +
    `export type Deployment = {
  chainId: number;
  deployer: \`0x\${string}\`;
  guardian: \`0x\${string}\`;
  guardianUntil: number;
  keeper: \`0x\${string}\`;
  usdg: \`0x\${string}\`;
  cube: \`0x\${string}\` | null;
  timelock: \`0x\${string}\`;
  points: \`0x\${string}\`;
  governor: \`0x\${string}\`;
  buyBurn: \`0x\${string}\`;
  vaults: \`0x\${string}\`;
  hunt: \`0x\${string}\`;
  targets: Record<string, number>;
  deployBlock: number;
};\n`,
);
console.log(`Exported ${Object.keys(C).length} ABIs${dep ? " and the Robinhood deployment" : " (no deployment yet)"} to app/src/generated`);
